package com.example.service

import android.app.Notification
import android.content.Context
import android.content.Intent
import android.os.Build
import android.provider.Settings
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import android.util.Log
import com.example.data.AppDatabase
import com.example.data.NotificationEntity
import com.example.engine.HeuristicEngine
import com.example.model.CapturedNotification
import com.example.model.RiskLevel
import com.example.model.ScanType
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.launch
import java.util.UUID

class NotificationReaderService : NotificationListenerService() {

    private val serviceScope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

    override fun onNotificationPosted(sbn: StatusBarNotification?) {
        super.onNotificationPosted(sbn)
        if (sbn == null) return

        val pkgName = sbn.packageName ?: return
        // Do not process notifications generated by PhishGuard itself
        if (pkgName == packageName) return

        val notification = sbn.notification ?: return
        val extras = notification.extras ?: return

        val title = extras.getCharSequence(Notification.EXTRA_TITLE)?.toString()?.trim() ?: ""
        val text = extras.getCharSequence(Notification.EXTRA_TEXT)?.toString()?.trim() ?: ""
        val bigText = extras.getCharSequence(Notification.EXTRA_BIG_TEXT)?.toString()?.trim() ?: ""
        val content = if (bigText.isNotBlank()) bigText else text

        // Ignore empty / system heartbeat notifications
        if (title.isBlank() && content.isBlank()) return

        val appName = try {
            val pm = packageManager
            val appInfo = pm.getApplicationInfo(pkgName, 0)
            pm.getApplicationLabel(appInfo).toString()
        } catch (_: Exception) {
            when {
                pkgName.contains("paisa") || pkgName.contains("nbu") -> "Google Pay"
                pkgName.contains("phonepe") -> "PhonePe"
                pkgName.contains("paytm") -> "Paytm"
                pkgName.contains("whatsapp") -> "WhatsApp"
                pkgName.contains("messaging") || pkgName.contains("mms") -> "SMS / Messages"
                pkgName.contains("sbi") -> "SBI YONO"
                pkgName.contains("hdfc") -> "HDFC Bank"
                pkgName.contains("icici") -> "iMobile ICICI"
                pkgName.contains("axis") -> "Axis Mobile"
                pkgName.contains("telegram") -> "Telegram"
                else -> pkgName.substringAfterLast('.').replaceFirstChar { it.uppercase() }
            }
        }

        val combinedForAnalysis = if (title.isNotBlank()) "$title: $content" else content
        val analysis = HeuristicEngine.analyze(combinedForAnalysis, ScanType.SMS_MESSAGE)

        val riskScore = analysis.heuristicScore
        val riskLevel = when {
            riskScore >= 70 -> RiskLevel.HIGH
            riskScore >= 40 -> RiskLevel.MEDIUM
            else -> RiskLevel.LOW
        }
        val topThreat = analysis.indicators.firstOrNull()?.title

        val captured = CapturedNotification(
            id = UUID.randomUUID().toString(),
            packageName = pkgName,
            appName = appName,
            title = title,
            content = content,
            timestamp = if (sbn.postTime > 0) sbn.postTime else System.currentTimeMillis(),
            isFlagged = riskLevel == RiskLevel.HIGH, // Proactively pre-flag high-risk threats
            flagReason = if (riskLevel == RiskLevel.HIGH) topThreat ?: "Urgent Digital Scam Signature" else null,
            flaggedAt = if (riskLevel == RiskLevel.HIGH) System.currentTimeMillis() else null,
            riskScore = riskScore,
            riskLevel = riskLevel,
            detectedScamType = topThreat
        )

        serviceScope.launch {
            try {
                val db = AppDatabase.getDatabase(applicationContext)
                db.notificationDao().insert(NotificationEntity.fromDomain(captured))
            } catch (e: Exception) {
                Log.e("NotifReaderService", "Failed to record notification", e)
            }
        }
    }

    companion object {
        fun isPermissionGranted(context: Context): Boolean {
            return try {
                val enabledListeners = Settings.Secure.getString(
                    context.contentResolver,
                    "enabled_notification_listeners"
                ) ?: return false
                val myPackage = context.packageName
                enabledListeners.split(":").any {
                    it.startsWith("$myPackage/") || it == myPackage
                }
            } catch (_: Exception) {
                false
            }
        }

        fun openSettings(context: Context) {
            try {
                val intent = Intent(Settings.ACTION_NOTIFICATION_LISTENER_SETTINGS).apply {
                    flags = Intent.FLAG_ACTIVITY_NEW_TASK
                }
                context.startActivity(intent)
            } catch (_: Exception) {
                // Fallback to general settings if specific action fails
                try {
                    val fallbackIntent = Intent(Settings.ACTION_SETTINGS).apply {
                        flags = Intent.FLAG_ACTIVITY_NEW_TASK
                    }
                    context.startActivity(fallbackIntent)
                } catch (_: Exception) {}
            }
        }
    }
}
